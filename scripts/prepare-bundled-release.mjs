#!/usr/bin/env node
/** Generate private server bootstrap bytes from the verified release artifact. */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = fileURLToPath(new URL("../", import.meta.url));
const metadata = JSON.parse(
  readFileSync(path.join(root, "lib/content/bundled-release.json"), "utf8"),
);
if (
  metadata.debuggable !== false ||
  metadata.packageId !== "com.bulmartech.danakeluarga" ||
  metadata.status !== "published" ||
  !/^[a-f0-9]{64}$/.test(metadata.sha256) ||
  !/^dana-keluarga-[A-Za-z0-9._-]+-release-[a-f0-9]{8}\.apk$/.test(
    metadata.fileName,
  )
)
  throw new Error("Metadata APK release bawaan tidak valid.");
const bytes = readFileSync(
  path.join(root, "artifacts/releases", metadata.fileName),
);
if (
  bytes.length !== metadata.fileSize ||
  createHash("sha256").update(bytes).digest("hex") !== metadata.sha256
)
  throw new Error("Ukuran/checksum APK release tidak sesuai metadata.");
const target = path.join(root, "lib/server/bundled-apk-bytes.ts");
const value =
  "// Generated by scripts/prepare-bundled-release.mjs. Server-only private R2 bootstrap.\nexport const bundledApkBase64 = " +
  JSON.stringify(bytes.toString("base64")) +
  ";\n";
if (!existsSync(target) || readFileSync(target, "utf8") !== value)
  writeFileSync(target, value);
console.log(
  "APK release " +
    metadata.versionName +
    " siap: checksum cocok, bootstrap hanya di server.",
);
